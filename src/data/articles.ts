export function getPublishedArticles(): Article[] {
  return ARTICLES.filter(a => a.status === 'published');
}

export function getArticleBySlug(slug: string): Article | undefined {
  return ARTICLES.find(a => a.slug === slug);
}

export function getArticleById(id: string): Article | undefined {
  return ARTICLES.find(a => a.id === id);
}

export function getArticlesByCategory(category: CategorySlug): Article[] {
  return ARTICLES.filter(a => a.category === category && a.status === 'published');
}

export function getArticlesByAuthor(authorId: string): Article[] {
  return ARTICLES.filter(a => a.authorId === authorId && a.status === 'published');
}

export function getArticlesByTag(tag: string): Article[] {
  return ARTICLES.filter(a => a.tags.includes(tag) && a.status === 'published');
}

export function getAllTags(): { tag: string; count: number }[] {
  const tagMap = new Map<string, number>();
  ARTICLES.filter(a => a.status === 'published').forEach(article => {
    article.tags.forEach(tag => {
      tagMap.set(tag, (tagMap.get(tag) || 0) + 1);
    });
  });
  return Array.from(tagMap.entries())
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count);
}
